const unsigned char *hub75_font_glyph(char c) {
  unsigned char u = (unsigned char)c;

  if (u >= 'A' && u <= 'Z') {
    u = (unsigned char)(u - 'A' + 'a');
  }
  if (u < 32 || u > 127) {
    u = ' ';
  }
  return FONT[u - 32];
}
