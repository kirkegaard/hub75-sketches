static uint16_t bg;
static uint16_t ink;
static uint16_t rule;

static const GbGlyph *glyph_for(unsigned char c) {
  if (c < GB_FIRST || c >= GB_FIRST + GB_COUNT) {
    return 0;
  }
  if (GB_GLYPH[c - GB_FIRST].width == 0) {
    return 0;
  }
  return &GB_GLYPH[c - GB_FIRST];
}

static int text_width(const char *s) {
  int w = 0;

  for (; *s != '\0'; s++) {
    const GbGlyph *g = glyph_for((unsigned char)*s);
    w += g ? g->width : 4;
  }
  return w;
}

static void text(int x, int y, const char *s) {
  for (; *s != '\0'; s++) {
    const GbGlyph *g = glyph_for((unsigned char)*s);
    int row;
    int col;

    if (!g) {
      x += 4;
      continue;
    }
    if (g->stride != 0 && y < height && y + GB_ROWS > 0 && x < width &&
        x + g->width > 0) {
      for (row = 0; row < GB_ROWS; row++) {
        const uint8_t *bytes = GB_BITS + g->at + (unsigned)row * g->stride;
        for (col = 0; col < g->width; col++) {
          if (bytes[col >> 3] & (uint8_t)(0x80u >> (col & 7))) {
            point(x + col, y + row);
          }
        }
      }
    }
    x += g->width;
  }
}

void setup(void) {
  bg = color(15, 56, 15);
  ink = color(155, 188, 15);
  rule = color(48, 98, 48);
  strokeWeight(1);
}

void draw(void) {
  int span = text_width(LINE);
  int scroll;
  int x;
  int y = (height / 2) - 4;

  if (span < 1) {
    span = 1;
  }
  scroll = (int)((frameCount - 1) % (unsigned)span);
  background(bg);

  // text((width - text_width(TITLE_A)) / 2, (height / 2) - 8, TITLE_A);
  // text((width - text_width(TITLE_B)) / 2, (height / 2), TITLE_B);

  for (x = -scroll; x < width; x += span) {
    text(x, y, LINE);
  }
  stroke(rule);
}
